#!/usr/bin/env python3

def add_one(x):
    x += 1

number = 42
print(number)

add_one(number)

print(number)

# ภายในโปรแกรม ให้สร้างเมธอดชื่อ add_one
# เมธอดนี้รับ parameter มา 1 ค่า
# และทำการ เพิ่มค่าให้ parameter นั้นขึ้น 1

# ในส่วนหลักของโปรแกรม
# ให้ประกาศตัวแปรหนึ่งตัว
# แสดงค่าของตัวแปรนั้น
# จากนั้นเรียกใช้เมธอด add_one

# หลังจากเรียกเมธอดแล้ว
# ให้แสดงค่าของตัวแปรเดิมอีกครั้ง